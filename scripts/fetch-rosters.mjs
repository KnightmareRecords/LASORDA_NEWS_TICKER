// Builds lib/rosters.ts: every NFL/NBA/MLB/NHL player's name → our team key, from ESPN's team rosters.
// Runs on Jay's computer (DEPLOY.cmd runs it before publishing), so the live site does no roster work at all.
// If ESPN can't be reached, the existing lib/rosters.ts is kept unchanged.
// Run from the project folder:  node scripts/fetch-rosters.mjs
import { readFile, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { build } from 'esbuild';

const OUT = 'lib/rosters.ts';
const LEAGUES = [
  { league: 'NFL', path: 'football/nfl' },
  { league: 'NBA', path: 'basketball/nba' },
  { league: 'MLB', path: 'baseball/mlb' },
  { league: 'NHL', path: 'hockey/nhl' },
];

const bundled = await build({ entryPoints: [path.resolve('lib/teams.ts')], bundle: true, write: false, platform: 'node', format: 'esm' });
const { TEAMS } = await import(`data:text/javascript;base64,${Buffer.from(bundled.outputFiles[0].text).toString('base64')}`);

/** Same normalization as lib/players.ts: lowercase, no accents/periods, no Jr./Sr./II/III. */
const normalize = (name) => name.normalize('NFD').replace(/[̀-ͯ]/g, '').toLowerCase().replace(/[.’']/g, '').replace(/\b(?:jr|sr|ii|iii|iv)\b/g, '').replace(/[^a-z -]/g, ' ').replace(/\s+/g, ' ').trim();

async function json(url) {
  const response = await fetch(url, { signal: AbortSignal.timeout(20_000), headers: { Accept: 'application/json' } });
  if (!response.ok) throw new Error(`${response.status} ${url}`);
  return response.json();
}

const players = new Map(); // name -> team key, or null when two teams have a player with that name
let teamsDone = 0;
let failures = 0;
for (const { league, path: sportPath } of LEAGUES) {
  const list = (await json(`https://site.api.espn.com/apis/site/v2/sports/${sportPath}/teams`)).sports[0].leagues[0].teams.map((entry) => entry.team);
  const ours = TEAMS.filter((team) => team.league === league);
  for (const espnTeam of list) {
    const team = ours.find((candidate) => candidate.name.toLowerCase() === String(espnTeam.name ?? '').toLowerCase())
      ?? ours.find((candidate) => candidate.key === `${league.toLowerCase()}-${String(espnTeam.abbreviation).toLowerCase()}`);
    if (!team) {
      console.warn(`no match for ${league} ${espnTeam.displayName}`);
      continue;
    }
    try {
      const roster = await json(`https://site.api.espn.com/apis/site/v2/sports/${sportPath}/teams/${espnTeam.id}/roster`);
      // NFL/NHL group players by position ({ items: [...] }); NBA/MLB list them directly.
      const athletes = (roster.athletes ?? []).flatMap((entry) => (Array.isArray(entry.items) ? entry.items : [entry]));
      for (const athlete of athletes) {
        const name = normalize(athlete.fullName ?? athlete.displayName ?? '');
        if (!name.includes(' ')) continue;
        players.set(name, players.has(name) && players.get(name) !== team.key ? null : team.key);
      }
      teamsDone += 1;
    } catch (error) {
      failures += 1;
      console.warn(`roster failed: ${team.key}: ${error.message}`);
    }
  }
}

// Keep the old file if the download clearly didn't work (network down, ESPN changed).
if (teamsDone < 100 || failures > 10) {
  console.error(`Only ${teamsDone} rosters loaded (${failures} failed): keeping the existing ${OUT}.`);
  process.exit(0);
}
const unique = [...players.entries()].filter(([, key]) => key).sort(([a], [b]) => a.localeCompare(b));
const today = new Date().toISOString().slice(0, 10);
const body = `// GENERATED by scripts/fetch-rosters.mjs from ESPN team rosters on ${today} (DEPLOY.cmd refreshes it).
// Player full name (normalized, see lib/players.ts) → team key. Names shared by players on two teams are left out.
// Used only when a story names no team at all ("Kyler Murray out vs. Bills" → Vikings).

export const ROSTERS_UPDATED = '${today}';

export const PLAYER_TEAMS: Record<string, string> = {
${unique.map(([name, key]) => `  ${JSON.stringify(name)}: '${key}',`).join('\n')}
};
`;
const previous = await readFile(OUT, 'utf8').catch(() => '');
if (previous.replace(/\d{4}-\d{2}-\d{2}/g, '') === body.replace(/\d{4}-\d{2}-\d{2}/g, '')) {
  console.log(`Rosters unchanged (${unique.length} players).`);
} else {
  await writeFile(OUT, body);
  console.log(`Wrote ${OUT}: ${unique.length} players from ${teamsDone} teams.`);
}
