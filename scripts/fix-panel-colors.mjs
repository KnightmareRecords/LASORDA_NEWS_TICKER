// Finds teams whose logo is (mostly) invisible on their own panel color and picks a better panel
// background for each: the team's second color or white, whichever shows the logo best while the
// lettering (team's main color) stays readable. Writes lib/panel-backgrounds.ts.
// Run from the project folder after changing logos or colors:  node scripts/fix-panel-colors.mjs
import { writeFile } from 'node:fs/promises';
import { createRequire } from 'node:module';
import path from 'node:path';
import { build } from 'esbuild';
import sharp from 'sharp';

const project = process.cwd();
const OUT = 'lib/panel-backgrounds.ts';
// Share of the logo's visible pixels allowed to blend into the panel before we change the panel.
const BLEND_LIMIT = 0.6;
const BLEND_CONTRAST = 1.6;

// Load lib/teams.ts without its current overrides (so results don't depend on the last run).
await writeFile(OUT, 'export const PANEL_BACKGROUNDS: Record<string, string> = {};\n');
const bundled = await build({ entryPoints: [path.join(project, 'lib/teams.ts')], bundle: true, write: false, platform: 'node', format: 'esm' });
const { TEAMS, panelColors, teamLabel } = await import(`data:text/javascript;base64,${Buffer.from(bundled.outputFiles[0].text).toString('base64')}`);
createRequire(import.meta.url);

const channel = (v) => { const c = v / 255; return c <= 0.03928 ? c / 12.92 : ((c + 0.055) / 1.055) ** 2.4; };
const lum = ([r, g, b]) => 0.2126 * channel(r) + 0.7152 * channel(g) + 0.0722 * channel(b);
const rgb = (hex) => [1, 3, 5].map((i) => Number.parseInt(hex.slice(i, i + 2), 16));
const contrast = (a, b) => { const [hi, lo] = [lum(a), lum(b)].sort((x, y) => y - x); return (hi + 0.05) / (lo + 0.05); };

async function logoPixels(key) {
  try {
    const { data, info } = await sharp(path.join(project, 'public/teams', `${key}.png`)).ensureAlpha().raw().toBuffer({ resolveWithObject: true });
    const pixels = [];
    for (let i = 0; i < data.length; i += info.channels) if (data[i + 3] >= 128) pixels.push([data[i], data[i + 1], data[i + 2]]);
    return pixels;
  } catch {
    return null;
  }
}
const blendShare = (pixels, background) => pixels.filter((pixel) => contrast(pixel, rgb(background)) < BLEND_CONTRAST).length / pixels.length;

// Chosen by eye (2026-11-05): logos with a dark outline fool the pixel check.
const MANUAL = {
  'mlb-pit': '#27251F', // Pirates: gold P on a black panel
  'ncaa-mich': '#00274C', // Michigan: maize M on a navy panel
};

const overrides = [];
for (const team of TEAMS) {
  if (MANUAL[team.key]) {
    overrides.push({ key: team.key, background: MANUAL[team.key], label: `${teamLabel(team)} (set by hand)`, before: 1, after: 0 });
    continue;
  }
  const pixels = await logoPixels(team.key);
  if (!pixels || pixels.length === 0) continue;
  const current = panelColors(team).background;
  const currentShare = blendShare(pixels, current);
  if (currentShare <= BLEND_LIMIT) continue;
  // Candidates: second color, white. Lettering uses the main color, so it must be readable on it.
  const candidates = [team.secondary, '#FFFFFF']
    .filter((background) => background.toUpperCase() !== current.toUpperCase())
    .map((background) => ({ background, share: blendShare(pixels, background), text: contrast(rgb(background), rgb(team.primary)) }))
    .filter((option) => option.text >= 3 || contrast(rgb(option.background), [255, 255, 255]) >= 3 || contrast(rgb(option.background), [0, 0, 0]) >= 3)
    .sort((a, b) => a.share - b.share);
  // White keeps a clean, recognizable look (no "red Dodgers"): use it whenever it shows the logo
  // nearly as well as the team's second color.
  const white = candidates.find((option) => option.background === '#FFFFFF');
  const best = white && candidates[0] && white.share <= candidates[0].share + 0.1 ? white : candidates[0];
  if (best && best.share < currentShare - 0.25) {
    overrides.push({ key: team.key, background: best.background.toUpperCase(), label: teamLabel(team), before: currentShare, after: best.share });
  } else {
    console.warn(`no better panel for ${team.key} (${Math.round(currentShare * 100)}% blends)`);
  }
}

overrides.sort((a, b) => a.key.localeCompare(b.key));
await writeFile(
  OUT,
  `// GENERATED by scripts/fix-panel-colors.mjs: teams whose logo was mostly invisible on their own panel
// color get a different panel background (lettering then uses the team's main color, see panelColors).
// Re-run the script after changing logos or team colors.

export const PANEL_BACKGROUNDS: Record<string, string> = {
${overrides.map((o) => `  '${o.key}': '${o.background}', // ${o.label.includes('by hand') ? o.label : `${o.label}: ${Math.round(o.before * 100)}% → ${Math.round(o.after * 100)}% of logo blends in`}`).join('\n')}
};
`,
);
console.log(`${overrides.length} teams get a new panel background; wrote ${OUT}`);
