// Builds the college team list + logos from ESPN (same approach as the pro logos).
// Run from the project folder:  node scripts/fetch-college-teams.mjs
// Writes lib/college-teams.ts and public/teams/ncaa-<abbr>.png (200 px tall, trimmed, transparent).
// Major college sports only (Jay's choice): Power 4 conferences (SEC, Big Ten, Big 12, ACC),
// the Big East (basketball) and Notre Dame. Membership comes from ESPN's live standings, so
// re-running after conference realignment picks up the changes.
// Source: ESPN's Division I men's basketball team list (includes every major football school).
import { mkdir, readdir, unlink, writeFile } from 'node:fs/promises';
import sharp from 'sharp';

const LIST_URL = 'https://site.api.espn.com/apis/site/v2/sports/basketball/mens-college-basketball/teams?groups=50&limit=1000';
const MAJOR_CONFERENCES = [
  // [standings URL, conference ids]: ACC 1/2, Big 12 4/8, Big Ten 5/7, SEC 8/23, Big East 4 (basketball)
  ['https://site.api.espn.com/apis/v2/sports/football/college-football/standings?group=80', ['1', '4', '5', '8']],
  ['https://site.api.espn.com/apis/v2/sports/basketball/mens-college-basketball/standings?group=50', ['2', '8', '7', '23', '4']],
];
const EXTRA_SCHOOLS = ['87' /* Notre Dame (football independent, ACC in basketball) */];

const majorIds = new Set(EXTRA_SCHOOLS);
for (const [url, conferenceIds] of MAJOR_CONFERENCES) {
  const standings = await (await fetch(url)).json();
  for (const conference of standings.children ?? []) {
    if (!conferenceIds.includes(String(conference.id))) continue;
    for (const entry of conference.standings?.entries ?? []) majorIds.add(String(entry.team.id));
  }
}
console.log(`${majorIds.size} major-conference schools`);
const OUT_DATA = 'lib/college-teams.ts';
const OUT_DIR = 'public/teams';

// Jay's preferred short names where ESPN's abbreviation isn't the common one.
const ABBR_OVERRIDES = { 2390: 'UM' /* Miami (FL): ESPN uses MIA */, 41: 'UCONN' /* ESPN: CONN */, 245: 'TAMU' /* ESPN: TA&M */ };

const hex = (value, fallback) => (/^[0-9a-f]{6}$/i.test(value ?? '') ? `#${value.toUpperCase()}` : fallback);

const response = await fetch(LIST_URL);
if (!response.ok) throw new Error(`ESPN list: ${response.status}`);
const teams = (await response.json()).sports[0].leagues[0].teams.map((entry) => entry.team).filter((team) => majorIds.has(String(team.id)));
console.log(`${teams.length} schools kept`);
// Remove logos of schools no longer on the list (e.g. after realignment).
for (const file of await readdir(OUT_DIR).catch(() => [])) if (file.startsWith('ncaa-')) await unlink(`${OUT_DIR}/${file}`);

const used = new Set();
const rows = [];
await mkdir(OUT_DIR, { recursive: true });
for (const team of teams) {
  const abbr = (ABBR_OVERRIDES[team.id] ?? team.abbreviation).toUpperCase();
  let key = `ncaa-${abbr.toLowerCase().replace(/[^a-z0-9]+/g, '')}`;
  if (used.has(key)) key = `${key}-${team.id}`;
  used.add(key);
  const row = {
    key,
    espnId: team.id,
    abbr,
    school: team.location,
    name: team.name,
    primary: hex(team.color, '#333F48'),
    secondary: hex(team.alternateColor, '#FFFFFF'),
  };
  rows.push(row);
  const logo = team.logos?.find((item) => item.rel.includes('default'))?.href;
  if (!logo) {
    console.warn(`no logo: ${abbr} ${team.displayName}`);
    continue;
  }
  try {
    const image = await fetch(logo);
    if (!image.ok) throw new Error(String(image.status));
    const buffer = Buffer.from(await image.arrayBuffer());
    await sharp(buffer).trim().resize({ height: 200, width: 400, fit: 'inside' }).png().toFile(`${OUT_DIR}/${key}.png`);
  } catch (error) {
    console.warn(`logo failed: ${abbr} ${team.displayName}: ${error.message}`);
  }
}

rows.sort((a, b) => a.abbr.localeCompare(b.abbr));
const lines = rows.map((row) => `  c(${JSON.stringify(row.key)}, ${JSON.stringify(row.espnId)}, ${JSON.stringify(row.abbr)}, ${JSON.stringify(row.school)}, ${JSON.stringify(row.name)}, '${row.primary}', '${row.secondary}'),`);
await writeFile(
  OUT_DATA,
  `// GENERATED by scripts/fetch-college-teams.mjs from ESPN (major conferences only). Re-run that script to refresh.
// Shown on the ticker by their short name (abbr); colors are ESPN's team colors.

export type CollegeTeam = { key: string; espnId: string; abbr: string; school: string; name: string; primary: string; secondary: string };

const c = (key: string, espnId: string, abbr: string, school: string, name: string, primary: string, secondary: string): CollegeTeam => ({ key, espnId, abbr, school, name, primary, secondary });

export const COLLEGE_TEAMS: CollegeTeam[] = [
${lines.join('\n')}
];
`,
);
console.log(`wrote ${rows.length} teams to ${OUT_DATA}`);

// Keep public/teams/LOGO-FILE-NAMES.txt in step: replace its college section.
const LIST_FILE = `${OUT_DIR}/LOGO-FILE-NAMES.txt`;
const { readFile } = await import('node:fs/promises');
const current = await readFile(LIST_FILE, 'utf8').catch(() => '');
const MARK = '\nCOLLEGE (major conferences, generated by scripts/fetch-college-teams.mjs):\n';
const collegeSection = `${MARK}${rows.map((row) => `  ${row.key}.png   ${row.abbr} — ${row.school} ${row.name}`).join('\n')}\n`;
await writeFile(LIST_FILE, `${current.split(MARK)[0].replace(/\s+$/, '')}\n${collegeSection}`);
console.log(`updated ${LIST_FILE}`);
